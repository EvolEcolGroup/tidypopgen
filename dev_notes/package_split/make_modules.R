#' Assign each path the module of the first matching rule
#'
#' @param paths character vector of file paths, relative to the repository.
#' @param rules tibble with columns `pattern`, `module` and `note`.
#' @return a tibble with columns `path`, `module`, `note` and `rule` (the
#'   index of the matching rule, `NA` if none matched).
#' @examples
#' assign_module("R/gen_tibble.R", rules)
assign_module <- function(paths, rules) {
  # index of the first rule matching each path
  rule <- vapply(
    paths,
    function(path) {
      hit <- which(vapply(rules$pattern, grepl, logical(1), x = path))
      if (length(hit) == 0) NA_integer_ else hit[1]
    },
    integer(1)
  )
  tibble::tibble(
    path = paths,
    module = rules$module[rule],
    note = rules$note[rule],
    rule = unname(rule)
  )
}

# tracked files in the mapped folders
paths <- system2("git", c("ls-files", folders), stdout = TRUE)

modules <- assign_module(paths, rules)

# every file must match a rule
unassigned <- modules$path[is.na(modules$rule)]
if (length(unassigned) > 0) {
  stop(
    "files that match no rule:\n",
    paste(unassigned, collapse = "\n"),
    call. = FALSE
  )
}

# every rule should match at least one file (a stale rule hints at a rename)
unused <- setdiff(seq_len(nrow(rules)), modules$rule)
if (length(unused) > 0) {
  warning(
    "rules that match no file:\n",
    paste(rules$pattern[unused], collapse = "\n"),
    call. = FALSE
  )
}

